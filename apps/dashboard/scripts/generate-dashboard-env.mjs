#!/usr/bin/env node
/**
 * Generates apps/dashboard/src/environments/environment.generated.ts from the
 * process environment plus the repo `.env` files.
 *
 * The dashboard must never hardcode a Supabase URL or key in committed source.
 * `angular.json` swaps `src/environments/environment.ts` for the generated module
 * in every build configuration, so builds and `ng serve` pick up whatever
 * `PUBLIC_SUPABASE_URL` / `PUBLIC_SUPABASE_ANON_KEY` are exported or present in
 * `.env` / `.env.local`.
 *
 * Usage:
 *   node scripts/generate-dashboard-env.mjs [--production]
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const appDir = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const repoRoot = resolve(appDir, '..', '..');
const generatedPath = join(appDir, 'src', 'environments', 'environment.generated.ts');

const REQUIRED_KEYS = ['PUBLIC_SUPABASE_URL', 'PUBLIC_SUPABASE_ANON_KEY'];
const LEGACY_ALIASES = {
  PUBLIC_SUPABASE_URL: ['NEXT_PUBLIC_SUPABASE_URL'],
  PUBLIC_SUPABASE_ANON_KEY: ['NEXT_PUBLIC_SUPABASE_ANON_KEY']
};

// Lowest precedence first; process.env (below) always wins.
const ENV_FILES = [
  join(repoRoot, '.env'),
  join(repoRoot, '.env.local'),
  join(appDir, '.env'),
  join(appDir, '.env.local')
];

function parseEnvFile(path) {
  if (!existsSync(path)) return {};

  const parsed = {};

  for (const rawLine of readFileSync(path, 'utf8').split(/\r?\n/)) {
    const line = rawLine.trim();
    if (!line || line.startsWith('#')) continue;

    const match = line.match(/^(?:export\s+)?([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*)$/);
    if (!match) continue;

    let value = match[2].trim();
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }

    parsed[match[1]] = value;
  }

  return parsed;
}

function readSource() {
  return ENV_FILES.reduce((acc, file) => Object.assign(acc, parseEnvFile(file)), {});
}

function resolveKey(env, key) {
  const candidates = [key, ...(LEGACY_ALIASES[key] ?? [])];

  for (const candidate of candidates) {
    const value = env[candidate];
    if (typeof value === 'string' && value.trim().length > 0) return value.trim();
  }

  return '';
}

function main() {
  const env = { ...readSource(), ...process.env };
  const production = process.argv.includes('--production');

  const values = {
    PUBLIC_SUPABASE_URL: resolveKey(env, 'PUBLIC_SUPABASE_URL'),
    PUBLIC_SUPABASE_ANON_KEY: resolveKey(env, 'PUBLIC_SUPABASE_ANON_KEY')
  };

  const contents = `// Generated by scripts/generate-dashboard-env.mjs - do not edit, do not commit.
// Values come from the process env and the repo .env files at build time.
export const environment = {
  production: ${production},
  supabaseUrl: ${JSON.stringify(values.PUBLIC_SUPABASE_URL)},
  supabaseAnonKey: ${JSON.stringify(values.PUBLIC_SUPABASE_ANON_KEY)}
};
`;

  writeFileSync(generatedPath, contents);

  const missing = REQUIRED_KEYS.filter((key) => values[key].length === 0);
  const target = relative(repoRoot, generatedPath).replace(/\\/g, '/');
  const status = REQUIRED_KEYS.map((key) => `${key}=${values[key] ? 'set' : 'MISSING'}`).join(' ');

  console.log(`[generate-dashboard-env] wrote ${target} (production=${production}) ${status}`);

  if (missing.length > 0) {
    console.error(
      `[generate-dashboard-env] WARNING: ${missing.join(', ')} not found. ` +
        'Local dev reads .env.local; Vercel injects PUBLIC_* for deployed builds.'
    );
  }
}

export { parseEnvFile, readSource, resolveKey };

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  main();
}
